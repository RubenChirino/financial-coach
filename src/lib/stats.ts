/** Small descriptive statistics shared by the recurring detector and the forecast. */

/** Middle value; the mean of the two middle values for an even count. `NaN` for none. */
export function median(nums: number[]): number {
  if (nums.length === 0) return Number.NaN;
  const sorted = [...nums].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0
    ? ((sorted[mid - 1] as number) + (sorted[mid] as number)) / 2
    : (sorted[mid] as number);
}

/** Arithmetic mean; 0 for none. */
export function mean(nums: number[]): number {
  if (nums.length === 0) return 0;
  return nums.reduce((s, n) => s + n, 0) / nums.length;
}

/** Population standard deviation; 0 for fewer than two values. */
export function stdDev(nums: number[]): number {
  if (nums.length < 2) return 0;
  const m = mean(nums);
  const variance = nums.reduce((s, n) => s + (n - m) ** 2, 0) / nums.length;
  return Math.sqrt(variance);
}
